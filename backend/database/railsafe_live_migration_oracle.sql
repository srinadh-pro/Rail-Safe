-- =============================================================
-- RailSafe - Oracle 19c migration for the additive live layer
-- Run as the RAILSAFE user AFTER the original schema exists.
-- Safe to re-run: every object is created only when missing.
-- =============================================================
-- New objects in this migration:
--   * notifications.dedupe_key (if the original table did not have it)
--   * train_snapshots
--   * route_alternatives (+ synthetic flag on older tables)
--   * notification_preferences
--   * train_master (synthetic demo catalogue)
--   * train_tracking (synthetic gate/train assignments)
--
-- Spring Boot runs with ddl-auto=update, so it can also create these
-- automatically. Use this script when you manage the schema manually.
-- =============================================================

SET SERVEROUTPUT ON;

-- -------------------------------------------------------------
-- 1. notifications.dedupe_key
-- -------------------------------------------------------------
DECLARE
    v_exists NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_exists
      FROM user_tab_columns
     WHERE table_name = 'NOTIFICATIONS'
       AND column_name = 'DEDUPE_KEY';

    IF v_exists = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE notifications ADD (dedupe_key VARCHAR2(120))';

        -- Existing rows predate dedupe. Give each one a unique audit key so the
        -- NOT NULL + UNIQUE constraints can be applied without deleting history.
        EXECUTE IMMEDIATE 'UPDATE notifications
                              SET dedupe_key = ''legacy:'' || TO_CHAR(id)
                            WHERE dedupe_key IS NULL';

        EXECUTE IMMEDIATE 'ALTER TABLE notifications MODIFY (dedupe_key VARCHAR2(120) NOT NULL)';
        EXECUTE IMMEDIATE 'ALTER TABLE notifications
                           ADD CONSTRAINT uk_notification_dedupe UNIQUE (dedupe_key)';

        DBMS_OUTPUT.PUT_LINE('Applied notifications.dedupe_key.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('notifications.dedupe_key already present.');
    END IF;
END;
/

-- -------------------------------------------------------------
-- 2. train_snapshots
-- -------------------------------------------------------------
DECLARE
    v_exists NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_exists FROM user_tables WHERE table_name = 'TRAIN_SNAPSHOTS';
    IF v_exists = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE train_snapshots (
                id                 NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
                provider           VARCHAR2(120) NOT NULL,
                data_mode          VARCHAR2(20)  NOT NULL,
                train_number       VARCHAR2(40)  NOT NULL,
                train_name         VARCHAR2(160) NOT NULL,
                direction          VARCHAR2(20),
                latitude           FLOAT(126),
                longitude          FLOAT(126),
                speed_kmph         FLOAT(126),
                gate_code          VARCHAR2(30),
                eta_at_gate        TIMESTAMP(6) WITH TIME ZONE,
                scheduled_arrival  TIMESTAMP(6) WITH TIME ZONE,
                train_status       VARCHAR2(20),
                observed_at        TIMESTAMP(6) WITH TIME ZONE,
                recorded_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
                feed_stale         NUMBER(1) DEFAULT 0 NOT NULL,
                CONSTRAINT pk_train_snapshots PRIMARY KEY (id),
                CONSTRAINT ck_train_snapshots_stale CHECK (feed_stale IN (0, 1))
            )';
        EXECUTE IMMEDIATE 'CREATE INDEX idx_train_snapshots_recorded ON train_snapshots (recorded_at)';
        EXECUTE IMMEDIATE 'CREATE INDEX idx_train_snapshots_gate ON train_snapshots (gate_code)';
        EXECUTE IMMEDIATE 'CREATE INDEX idx_train_snapshots_train ON train_snapshots (train_number)';
        DBMS_OUTPUT.PUT_LINE('Created train_snapshots.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('train_snapshots already present.');
    END IF;
END;
/

