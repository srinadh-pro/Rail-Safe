import React, { useMemo } from 'react';
import { formatDateTime, timeAgo } from '../format.js';

const TYPE_META = {
  GATE_CLOSED: { label: 'Gate closed', tone: 'red', icon: '⛔' },
  GATE_OPENED: { label: 'Gate reopened', tone: 'green', icon: '✅' },
  GATE_UNKNOWN: { label: 'Status unknown', tone: 'grey', icon: '❔' },
  TRAIN_APPROACHING: { label: 'Train approaching', tone: 'orange', icon: '🚆' },
  TRAIN_CROSSING: { label: 'Train crossing', tone: 'red', icon: '🚦' },
  TRAIN_PASSED: { label: 'Train passed', tone: 'green', icon: '✅' },
  GATE_CLOSING_SOON: { label: 'Closing soon', tone: 'orange', icon: '⏳' },
  GATE_OPENING_SOON: { label: 'Opening soon', tone: 'red', icon: '⏱️' },
  ALTERNATIVE_ROUTE: { label: 'Alternative route', tone: 'blue', icon: '🗺️' },
  REPORT: { label: 'Report update', tone: 'blue', icon: '📝' },
  SYSTEM: { label: 'System', tone: 'grey', icon: 'ℹ️' }
};

function metaFor(type) {
  return TYPE_META[type] || { label: 'Alert', tone: 'grey', icon: '🔔' };
}

function PermissionCard({ permission, onRequest }) {
  if (permission === 'granted') {
    return (
      <div className="notice notice-green">
        <strong>Browser notifications are enabled.</strong> New alerts appear while this dashboard is open.
        Delivery in the background requires the browser to keep the tab open; RailSafe does not use a
        service worker or push server.
      </div>
    );
  }

  if (permission === 'denied') {
    return (
      <div className="notice notice-orange">
        <strong>Browser notifications are blocked.</strong> Alerts still appear in the history below and in
        the existing Alerts page. Change the site permission in your browser settings to enable pop-ups.
      </div>
    );
  }

  if (permission === 'unsupported') {
    return (
      <div className="notice notice-grey">
        <strong>This browser does not support notifications.</strong> The in-app notification history
        below still updates.
      </div>
    );
  }

  return (
    <div className="notice notice-blue permission-row">
      <div>
        <strong>Allow browser alerts?</strong> RailSafe will ask your browser for permission. You can revoke
        it at any time, and history is always available below.
      </div>
      <button type="button" className="btn btn-primary" onClick={onRequest}>
        Enable browser alerts
      </button>
    </div>
  );
}

function PreferenceToggle({ label, description, checked, disabled, onChange, note }) {
  return (
    <label className={`pref-row ${disabled ? 'pref-disabled' : ''}`}>
      <span>
        <strong>{label}</strong>
        <small>{description}</small>
        {note ? <small className="pref-note">{note}</small> : null}
      </span>
      <input
        type="checkbox"
        checked={Boolean(checked)}
        disabled={disabled}
        onChange={(event) => onChange(event.target.checked)}
      />
    </label>
  );
}

export default function NotificationsPanel({ user, notifications }) {
  const {
    items,
    loading,
    error,
    permission,
    preferences,
    savingPreferences,
    requestPermission,
    markRead,
    markAllRead,
    savePreferences,
    refresh
  } = notifications;

  const unread = useMemo(() => items.filter((item) => !item.read).length, [items]);

  const updatePreference = async (patch) => {
    if (!preferences) return;
    try {
      await savePreferences({
        browserEnabled: preferences.browserEnabled,
        emailEnabled: preferences.emailEnabled,
        smsEnabled: preferences.smsEnabled,
        ...patch
      });
    } catch {
      // The error is surfaced by the shared notifications hook.
    }
  };

  return (
    <section className="card notifications-card" aria-labelledby="notifications-heading">
      <div className="card-head">
        <div>
          <span className="eyebrow">Alert history</span>
          <h2 id="notifications-heading">Notifications</h2>
          <p className="muted">
            Gate, train and route alerts generated by server-side polling. Access is login-first: sign in
            with the role assigned to your account. Duplicate events are suppressed by a database dedupe key
            so the same alert is not shown twice.
          </p>
        </div>
        <span className={`tag ${unread ? 'tag-orange' : 'tag-grey'}`}>
          {unread} unread
        </span>
      </div>

      {!user ? (
        <div className="empty-state" role="status">
          <span className="empty-title">Sign in to see your notifications</span>
          <p>
            RailSafe is login-first. Live gate and train information is available only to signed-in users
            with an authorised role. Sign in to see your alert history, read status and delivery preferences.
          </p>
          <div className="empty-actions">
            <a className="btn btn-primary" href="/login.html">Log in</a>
            <a className="btn btn-ghost" href="/register.html">Create an account</a>
          </div>
        </div>
      ) : (
        <>
          <PermissionCard permission={permission} onRequest={requestPermission} />

          {permission === 'granted' && preferences ? (
            <div className="preferences">
              <div className="preferences-head">
                <div>
                  <span className="eyebrow">Delivery channels</span>
                  <h3>Notification preferences</h3>
                </div>
                {savingPreferences ? <span className="tag tag-grey">Saving…</span> : null}
              </div>

              <PreferenceToggle
                label="Browser notifications"
                description="Show a desktop notification while this dashboard tab is open."
                checked={preferences.browserEnabled}
                onChange={(value) => updatePreference({ browserEnabled: value })}
              />
              <PreferenceToggle
                label="Email alerts"
                description="Optional server-side email delivery."
                checked={preferences.emailEnabled}
                disabled={!preferences.emailChannelConfigured}
                note={preferences.emailChannelConfigured
                  ? 'Email is configured on this server.'
                  : 'Not configured on this server; enable spring.mail.* and railsafe.notifications.email.enabled.'}
                onChange={(value) => updatePreference({ emailEnabled: value })}
              />
              <PreferenceToggle
                label="SMS alerts"
                description="Optional server-side SMS delivery through a configured gateway."
                checked={preferences.smsEnabled}
                disabled={!preferences.smsChannelConfigured}
                note={preferences.smsChannelConfigured
                  ? 'SMS gateway is configured on this server.'
                  : 'Not configured on this server; set railsafe.notifications.sms.webhook-url.'}
                onChange={(value) => updatePreference({ smsEnabled: value })}
              />
            </div>
          ) : null}

          <div className="notifications-toolbar">
            <button type="button" className="btn btn-ghost" onClick={refresh} disabled={loading}>
              {loading ? 'Refreshing…' : 'Refresh'}
            </button>
            <button
              type="button"
              className="btn btn-ghost"
              onClick={markAllRead}
              disabled={!unread}
            >
              Mark all read
            </button>
          </div>

          {error ? <div className="notice notice-red" role="alert">{error}</div> : null}

          {items.length === 0 ? (
            <div className="empty-state" role="status">
              <span className="empty-title">No notifications yet</span>
              <p>
                Alerts appear here after the server detects a qualifying event.
              </p>
            </div>
          ) : (
            <ul className="notification-list">
              {items.map((item) => {
                const meta = metaFor(item.type);
                return (
                  <li
                    key={item.id}
                    className={`notification-item notification-${meta.tone} ${item.read ? 'notification-read' : 'notification-unread'}`}
                  >
                    <span className="notification-icon" aria-hidden="true">{meta.icon}</span>
                    <div className="notification-body">
                      <div className="notification-top">
                        <span className={`tag tag-${meta.tone}`}>{meta.label}</span>
                        {!item.read ? <span className="unread-dot" aria-label="Unread" /> : null}
                        <time dateTime={item.createdAt} title={formatDateTime(item.createdAt)}>
                          {timeAgo(item.createdAt)}
                        </time>
                      </div>
                      <strong className="notification-title">{item.title}</strong>
                      <p>{item.message}</p>
                      <div className="notification-meta">
                        {item.gateName ? (
                          <span>{item.gateName}{item.gateCode ? ` · ${item.gateCode}` : ''}</span>
                        ) : null}
                        {item.statusAtEvent ? <span>Status at event: {item.statusAtEvent}</span> : null}
                      </div>
                    </div>
                    {!item.read ? (
                      <button
                        type="button"
                        className="btn btn-ghost btn-small"
                        onClick={() => markRead(item.id)}
                        aria-label={`Mark notification ${item.id} as read`}
                      >
                        Mark read
                      </button>
                    ) : null}
                  </li>
                );
              })}
            </ul>
          )}

          <p className="safety-line">
            Browser alerts can be late or blocked by the operating system. They are assistance only. Never
            rely on this page instead of physical barriers, signals or railway staff.
          </p>
        </>
      )}
    </section>
  );
}
